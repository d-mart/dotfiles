#!/usr/bin/env bash
# Write ~/.tmux.conf.local with a curated status-line color scheme.
#
# .tmux.conf sets @status_*/@pane_*/@message_* defaults and then sources
# ~/.tmux.conf.local, so every color the status line and borders use is a tmux
# user option this file can override. ~/.tmux.conf.local is untracked and lives
# in $HOME, so re-theming never makes the dotfiles repo dirty.
#
# With no arguments the theme is derived from a stable per-machine ID (hardware
# UUID / machine-id / hostname), so each host looks distinct and re-running on
# the same host is a no-op visually.
#
# Usage:
#   bin/gen-tmux-theme.sh                  # deterministic theme for this host
#   bin/gen-tmux-theme.sh --random         # random theme (never the current one)
#   bin/gen-tmux-theme.sh --next | --prev  # step through the palette list
#   bin/gen-tmux-theme.sh --theme nord     # pick one by name
#   bin/gen-tmux-theme.sh --list           # show every palette, with swatches
#   bin/gen-tmux-theme.sh --preview        # mock status bar in every palette
#   bin/gen-tmux-theme.sh --preview nord   # one palette, plus borders/messages
#   bin/gen-tmux-theme.sh --current        # print the active theme name
#   bin/gen-tmux-theme.sh --icon "🛰️ "     # override the host icon
#   bin/gen-tmux-theme.sh --if-needed      # generate only if no local file exists
#   bin/gen-tmux-theme.sh --no-reload      # write the file, don't re-source tmux

set -euo pipefail

target="${HOME}/.tmux.conf.local"
marker="# generated by gen-tmux-theme.sh -- safe to regenerate"
keep_marker="# ---- local additions below are preserved across regeneration ----"

