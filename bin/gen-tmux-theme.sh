##############################
# Args
##############################
mode="host"
want_theme=""
icon_override=""
reload=1

while [ $# -gt 0 ]; do
  case "$1" in
    --random|-r)    mode="random" ;;
    --next|-n)      mode="next" ;;
    --prev|-p)      mode="prev" ;;
    --theme|-t)     mode="named"; want_theme="${2:-}"; shift ;;
    --theme=*)      mode="named"; want_theme="${1#*=}" ;;
    --list|-l)      mode="list" ;;
    --preview|-P)
      mode="preview"
      # optional theme name: consume it only if it isn't the next flag
      if [ $# -gt 1 ] && [ "${2#-}" = "$2" ]; then want_theme="$2"; shift; fi
      ;;
    --preview=*)    mode="preview"; want_theme="${1#*=}" ;;
    --current)      mode="current" ;;
    --if-needed)    mode="if-needed" ;;
    --icon)         icon_override="${2:-}"; shift ;;
    --icon=*)       icon_override="${1#*=}" ;;
    --no-reload)    reload=0 ;;
    -h|--help)      sed -n '2,25p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "Unknown argument: $1" >&2; exit 1 ;;
  esac
  shift
done

##############################
# Helpers
##############################
field() { printf '%s' "$1" | cut -d'|' -f"$2"; }

# Paint a truecolor swatch so --list and the summary show the actual colors.
swatch() {
  local hex="${1#\#}" text="${2:-  }"
  printf '\033[48;2;%d;%d;%dm%s\033[0m' \
    "$((16#${hex:0:2}))" "$((16#${hex:2:2}))" "$((16#${hex:4:2}))" "$text"
}

fg_esc() {
  local h="${1#\#}"
  printf '\033[38;2;%d;%d;%dm' "$((16#${h:0:2}))" "$((16#${h:2:2}))" "$((16#${h:4:2}))"
}

bg_esc() {
  local h="${1#\#}"
  printf '\033[48;2;%d;%d;%dm' "$((16#${h:0:2}))" "$((16#${h:2:2}))" "$((16#${h:4:2}))"
}

pad() { [ "$1" -gt 0 ] && printf '%*s' "$1" ''; }

# Mock up the real status line -- same segments, same order, same justification
# as the status-left/status-right in .tmux.conf -- so a preview shows how a
# palette actually reads rather than just listing its colors. The session name
# slot doubles as the theme label.
render_bar() {
  local t="$1" cols="$2"
  local name bg fg c1 c2 c3 c4 border
  name=$(field "$t" 1); bg=$(field "$t" 2); fg=$(field "$t" 3)
  c1=$(field "$t" 4);   c2=$(field "$t" 5); c3=$(field "$t" 6)
  c4=$(field "$t" 7);   border=$(field "$t" 8)

  # Widths are tracked by hand: escape sequences occupy no columns, and the
  # icon is a double-width emoji plus its trailing space.
  local left_w=$(( 3 + 2 + ${#name} + 6 + 3 ))
  local center_w=22
  local right_w=27

  local gap_l=$(( (cols - center_w) / 2 - left_w ))
  local gap_r=$(( cols - left_w - gap_l - center_w - right_w ))
  [ "$gap_l" -lt 1 ] && gap_l=1
  [ "$gap_r" -lt 1 ] && gap_r=1

  bg_esc "$bg"
  printf '%s' "$host_icon"
  fg_esc "$c1"; printf '◆ %s' "$name"
  fg_esc "$fg"; printf ':'
  fg_esc "$c2"; printf '1'
  fg_esc "$fg"; printf ':'
  fg_esc "$c3"; printf '1 '
  fg_esc "$border"; printf '<P>'
  pad "$gap_l"

  # window list: inactive, active (reverse video), inactive
  fg_esc "$c3"; printf ' 1:zsh '
  bg_esc "$c3"; fg_esc "$bg"; printf ' 2:vim '
  bg_esc "$bg"; fg_esc "$c3"; printf ' 3:logs '
  pad "$gap_r"

  # status-right. The hostname is hardcoded to tmux's "cyan" in .tmux.conf
  # rather than a theme color, so it is drawn that way here too.
  printf '\033[36mweb01 '
  fg_esc "$c3"; printf '12%% '
  fg_esc "$c4"; printf '0.84 '
  fg_esc "$c2"; printf '15 Sep '
  fg_esc "$c1"; printf '09:41'
  printf '\033[0m\n'
}

# The pane borders and message line a theme also controls, which the status
# bar alone doesn't show.
render_chrome() {
  local t="$1" cols="$2"
  local bg border active c2
  bg=$(field "$t" 2); c2=$(field "$t" 5); border=$(field "$t" 8); active=$(field "$t" 9)

  fg_esc "$border"; printf '%*s' "$cols" '' | tr ' ' '─'; printf '\033[0m\n'
  printf '  inactive pane border\n'
  fg_esc "$active"; printf '%*s' "$cols" '' | tr ' ' '─'; printf '\033[0m\n'
  printf '  active pane border\n'
  bg_esc "$border"; fg_esc "$c2"
  printf ' Reloaded! %*s' "$(( cols - 11 ))" ''
  printf '\033[0m\n'
}

theme_line() {
  local want="$1" t
  for t in "${themes[@]}"; do
    [ "$(field "$t" 1)" = "$want" ] && { printf '%s' "$t"; return 0; }
  done
  return 1
}

theme_index() {
  local want="$1" i=0
  while [ "$i" -lt "${#themes[@]}" ]; do
    [ "$(field "${themes[$i]}" 1)" = "$want" ] && { printf '%s' "$i"; return 0; }
    i=$((i + 1))
  done
  return 1
}

current_theme() {
  local name
  [ -f "$target" ] || return 1
  name=$(awk '/^# theme: /{print $3; exit}' "$target")
  [ -n "$name" ] || return 1
  printf '%s' "$name"
}

##############################
# Stable per-machine seed (same approach as gen-starship-theme.sh)
##############################
host_hash() {
  local seed="" hash=""
  if command -v ioreg &>/dev/null; then
    seed=$(ioreg -rd1 -c IOPlatformExpertDevice 2>/dev/null | awk -F'"' '/IOPlatformUUID/{print $4}')
  fi
  [ -z "$seed" ] && [ -r /etc/machine-id ] && seed=$(cat /etc/machine-id)
  [ -z "$seed" ] && [ -r /var/lib/dbus/machine-id ] && seed=$(cat /var/lib/dbus/machine-id)
  [ -z "$seed" ] && seed=$(hostname)

  if command -v shasum &>/dev/null; then
    hash=$(printf '%s' "$seed" | shasum -a 256 | awk '{print $1}')
  elif command -v sha256sum &>/dev/null; then
    hash=$(printf '%s' "$seed" | sha256sum | awk '{print $1}')
  else
    echo "Need shasum or sha256sum to derive a host theme" >&2
    exit 1
  fi
  printf '%s' "$hash"
}

hash=$(host_hash)
# Independent slices so the icon doesn't move in lockstep with the palette.
host_idx=$((16#${hash:0:8} % ${#themes[@]}))
icon_idx=$((16#${hash:8:8} % ${#icons[@]}))
host_icon="${icons[$icon_idx]}"

##############################
# Read-only modes
##############################
if [ "$mode" = "list" ]; then
  cur=$(current_theme || true)
  for t in "${themes[@]}"; do
    name=$(field "$t" 1)
    mark=" "; [ "$name" = "$cur" ] && mark="*"
    printf '%s %-16s ' "$mark" "$name"
    swatch "$(field "$t" 2)" "  "
    for f in 3 4 5 6 7 9; do swatch "$(field "$t" "$f")" "  "; done
    [ "$name" = "$(field "${themes[$host_idx]}" 1)" ] && printf ' (this host)'
    printf '\n'
  done
  exit 0
fi

if [ "$mode" = "preview" ]; then
  cols=$(tput cols 2>/dev/null || echo 80)
  [ "$cols" -gt 100 ] && cols=100
  [ "$cols" -lt 60 ] && cols=60

  if [ -n "$want_theme" ]; then
    theme=$(theme_line "$want_theme") || {
      echo "Unknown theme: $want_theme (try --list)" >&2; exit 1; }
    render_bar "$theme" "$cols"
    render_chrome "$theme" "$cols"
  else
    for t in "${themes[@]}"; do render_bar "$t" "$cols"; done
  fi
  exit 0
fi

if [ "$mode" = "current" ]; then
  name=$(current_theme) || { echo "no generated theme in $target" >&2; exit 1; }
  echo "$name"
  exit 0
fi

if [ "$mode" = "if-needed" ] && [ -e "$target" ]; then
  echo "$target already exists, leaving it alone"
  exit 0
fi

##############################
# Pick a theme
##############################
cur=$(current_theme || true)
cur_idx=""
[ -n "$cur" ] && cur_idx=$(theme_index "$cur" || true)

case "$mode" in
  named)
    theme=$(theme_line "$want_theme") || {
      echo "Unknown theme: $want_theme (try --list)" >&2; exit 1; }
    ;;
  random)
    # Never hand back the theme that's already applied, or nothing looks
    # like it happened.
    idx=$((RANDOM % ${#themes[@]}))
    if [ "${#themes[@]}" -gt 1 ] && [ -n "$cur_idx" ]; then
      while [ "$idx" = "$cur_idx" ]; do idx=$((RANDOM % ${#themes[@]})); done
    fi
    theme="${themes[$idx]}"
    ;;
  next)
    idx=$(( ( ${cur_idx:-$host_idx} + 1 ) % ${#themes[@]} ))
    theme="${themes[$idx]}"
    ;;
  prev)
    idx=$(( ( ${cur_idx:-$host_idx} + ${#themes[@]} - 1 ) % ${#themes[@]} ))
    theme="${themes[$idx]}"
    ;;
  *)
    theme="${themes[$host_idx]}"
    ;;
esac

name=$(field "$theme" 1)
bg=$(field "$theme" 2)
fg=$(field "$theme" 3)
c1=$(field "$theme" 4)
c2=$(field "$theme" 5)
c3=$(field "$theme" 6)
c4=$(field "$theme" 7)
border=$(field "$theme" 8)
active=$(field "$theme" 9)
icon="${icon_override:-$host_icon}"

##############################
# Write
##############################
# A file we didn't write is someone's hand-tuned config; keep a copy before
# replacing it.
if [ -e "$target" ] && ! grep -qF "$marker" "$target"; then
  cp "$target" "${target}.bak"
  echo "Backed up existing $target to ${target}.bak"
fi

# Anything the user appended below the keep marker survives regeneration.
custom=""
if [ -f "$target" ]; then
  custom=$(awk -v m="$keep_marker" 'found {print} $0 == m {found = 1}' "$target")
fi

tmp=$(mktemp)
cat > "$tmp" <<EOF
${marker}
# theme: ${name}
#
# Host-local tmux overrides. Regenerate with:
#   gen-tmux-theme.sh --random | --next | --theme <name> | --list

set -g @status_left_icon "${icon}"
set -g @status_left_extra "#[fg=${c1}]◆ "

set -g @status_bg_color "${bg}"
set -g @status_fg_color "${fg}"
set -g @status_color_1 "${c1}"
set -g @status_color_2 "${c2}"
set -g @status_color_3 "${c3}"
set -g @status_color_4 "${c4}"

set -g @pane_border_fg "${border}"
set -g @pane_border_bg "default"
set -g @pane_active_border_fg "${active}"

set -g @message_fg "${c2}"
set -g @message_bg "${border}"

${keep_marker}
EOF

[ -n "$custom" ] && printf '%s\n' "$custom" >> "$tmp"

mv "$tmp" "$target"
chmod 644 "$target"

##############################
# Apply
#
# status-bg and friends are set with `-F`, so the @vars are expanded once at
# source time -- changing them alone does nothing. Re-source the whole config,
# which is what prefix + r does.
##############################
if [ "$reload" -eq 1 ] && tmux info &>/dev/null; then
  tmux source-file "${HOME}/.tmux.conf" 2>/dev/null \
    && echo "Reloaded running tmux server" \
    || echo "Wrote $target (tmux reload failed; press prefix + r)"
fi

printf 'tmux theme: %s %s' "$name" "$icon"
swatch "$bg" "  "
for h in "$c1" "$c2" "$c3" "$c4" "$active"; do swatch "$h" "  "; done
printf '  -> %s\n' "$target"
